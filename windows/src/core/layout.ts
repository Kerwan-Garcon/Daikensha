/** The Shell panel's height: SHELL_MAX_H, or what the window has room for. */
export function shellHeight(windowH: number): number {
  return Math.max(300, Math.min(SHELL_MAX_H, (windowH > 0 ? windowH : SHELL_MAX_H) - 8));
}

