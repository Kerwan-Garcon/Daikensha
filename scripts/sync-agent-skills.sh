#!/usr/bin/env bash
# Vendors the third-party agent skills the project uses into .claude/skills/,
# at the exact upstream commits pinned below.
#
# Why vendored and not declared as plugins: plugins named in .claude/settings.json
# (enabledPlugins / extraKnownMarketplaces) do not load in Claude Code cloud
# sessions, while the repository's own .claude/skills/ does. Vendoring keeps the
# same skills everywhere the repository is opened, at a reviewed version.
#
#   ./scripts/sync-agent-skills.sh            # re-vendor the pinned commits
#   ./scripts/sync-agent-skills.sh --check    # fail if .claude/skills/ drifted
#
# To update: bump a SHA below, run the script, read the diff, commit.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SKILLS_DIR="${REPO_ROOT}/.claude/skills"
LICENSES_DIR="${REPO_ROOT}/.claude/vendor-licenses"

# name | repository | pinned commit
SOURCES=(
  "superpowers|https://github.com/obra/superpowers.git|2ce8aa15d05bd57213e6f746f953aafb7ded7a8b"
  "karpathy|https://github.com/multica-ai/andrej-karpathy-skills.git|2c606141936f1eeef17fa3043a72095b4765b9c2"
  "adhd|https://github.com/ayghri/i-have-adhd.git|1ecea1993b7fce257ffbd686c070948b5e07eda6"
)

# Superpowers skills left out: diagnosing-superpowers mines past session
# transcripts to file issues upstream, which has nothing to do with this project.
SUPERPOWERS_SKIP=("diagnosing-superpowers")

CHECK=0
[ "${1:-}" = "--check" ] && CHECK=1

WORK="$(mktemp -d)"
trap 'rm -rf "${WORK}"' EXIT
OUT="${WORK}/out"
mkdir -p "${OUT}/skills" "${OUT}/licenses"

fetch() { # name url sha
  local dir="${WORK}/src/$1"
  git init -q "${dir}"
  git -C "${dir}" fetch -q --depth 1 "$2" "$3"
  git -C "${dir}" checkout -q FETCH_HEAD
  echo "${dir}"
}

for entry in "${SOURCES[@]}"; do
  IFS='|' read -r name url sha <<<"${entry}"
  src="$(fetch "${name}" "${url}" "${sha}")"
  case "${name}" in
    superpowers)
      for skill in "${src}"/skills/*/; do
        skill_name="$(basename "${skill}")"
        [[ " ${SUPERPOWERS_SKIP[*]} " == *" ${skill_name} "* ]] && continue
        cp -R "${skill}" "${OUT}/skills/${skill_name}"
      done
      # Installed as a plugin, these skills are namespaced `superpowers:<name>`;
      # vendored in the project they are plain `<name>`.
      # perl, not sed: BSD sed (macOS) has no word boundary.
      grep -rlZ 'superpowers:' "${OUT}/skills" | xargs -0 perl -pi -e \
        's/superpowers:(brainstorming|dispatching-parallel-agents|executing-plans|finishing-a-development-branch|receiving-code-review|requesting-code-review|subagent-driven-development|systematic-debugging|test-driven-development|using-git-worktrees|using-superpowers|verification-before-completion|writing-plans|writing-skills)\b/$1/g'
      cp "${src}/LICENSE" "${OUT}/licenses/superpowers.LICENSE"
      ;;
    karpathy)
      cp -R "${src}/skills/karpathy-guidelines" "${OUT}/skills/karpathy-guidelines"
      # Upstream declares MIT (README, plugin.json, SKILL.md) but ships no LICENSE file.
      printf 'MIT, as declared by %s (README.md, .claude-plugin/plugin.json and SKILL.md front matter).\nNo LICENSE file ships upstream at commit %s.\n' "${url}" "${sha}" \
        >"${OUT}/licenses/andrej-karpathy-skills.LICENSE"
      ;;
    adhd)
      cp -R "${src}/skills/i-have-adhd" "${OUT}/skills/i-have-adhd"
      # Per-agent manifests for other runtimes (Gemini, OpenAI): not used here.
      rm -rf "${OUT}/skills/i-have-adhd/agents"
      cp "${src}/LICENSE" "${OUT}/licenses/i-have-adhd.LICENSE"
      ;;
  esac
done

{
  echo "# Vendored agent skills"
  echo
  echo "Generated by \`scripts/sync-agent-skills.sh\`; do not edit by hand."
  echo
  echo "| Source | Commit | Licence |"
  echo "| --- | --- | --- |"
  for entry in "${SOURCES[@]}"; do
    IFS='|' read -r name url sha <<<"${entry}"
    echo "| ${url%.git} | \`${sha:0:12}\` | MIT |"
  done
} >"${OUT}/licenses/README.md"

if [ "${CHECK}" -eq 1 ]; then
  # Project-owned skills (anything not vendored) are left out of the comparison.
  status=0
  for skill in "${OUT}"/skills/*/; do
    diff -r "${skill%/}" "${SKILLS_DIR}/$(basename "${skill}")" >/dev/null || { echo "drifted: $(basename "${skill}")"; status=1; }
  done
  diff -r "${OUT}/licenses" "${LICENSES_DIR}" >/dev/null || { echo "drifted: vendor-licenses"; status=1; }
  exit "${status}"
fi

mkdir -p "${SKILLS_DIR}"
for skill in "${OUT}"/skills/*/; do
  rm -rf "${SKILLS_DIR}/$(basename "${skill}")"
  cp -R "${skill}" "${SKILLS_DIR}/"
done
rm -rf "${LICENSES_DIR}"
cp -R "${OUT}/licenses" "${LICENSES_DIR}"
echo "Vendored $(find "${OUT}/skills" -mindepth 1 -maxdepth 1 -type d | wc -l | tr -d ' ') skills into .claude/skills/."
